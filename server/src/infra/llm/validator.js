import { DIAGRAM_EDGE_TYPES } from '../../models/Diagram.js';
import { ApiError } from '../../shared/errors.js';

const ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/;
const EDGE_TYPES = new Set(DIAGRAM_EDGE_TYPES);

// Layout and presentation are backend concerns. Reject model output that tries
// to supply coordinates, markup or rendering instructions instead of semantic
// diagram data.
const FORBIDDEN_NODE_KEYS = [
  'x', 'y', 'width', 'height', 'position', 'coordinates', 'icon', 'iconName',
  'iconify', 'svg', 'html', 'imagePrompt', 'render', 'style', 'color',
];
const FORBIDDEN_DIAGRAM_KEYS = [
  'svg', 'html', 'imagePrompt', 'layout', 'positions', 'coordinates', 'render',
];
const FORBIDDEN_LAYOUT_KEYS = [
  'x', 'y', 'width', 'height', 'position', 'coordinates', 'points', 'route',
  'path', 'bendPoints', 'style', 'color', 'icon', 'iconName', 'svg', 'html',
];

function fail(message) {
  throw new ApiError(422, `Invalid diagram: ${message}`);
}

function isObject(value) {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function text(value, field, { required = true, max = 100 } = {}) {
  if (value === undefined || value === null) {
    if (required) fail(`${field} is required`);
    return '';
  }
  if (typeof value !== 'string') fail(`${field} must be text`);
  const clean = value.replace(/\s+/g, ' ').trim();
  if (required && !clean) fail(`${field} cannot be empty`);
  if (clean.length > max) fail(`${field} must be ${max} characters or fewer`);
  return clean;
}

function identifier(value, field) {
  const id = text(value, field, { max: 64 });
  if (!ID_PATTERN.test(id)) {
    fail(`${field} must start with a letter or number and use only letters, numbers, - and _`);
  }
  return id;
}

function array(value, field) {
  if (value === undefined || value === null) return [];
  if (!Array.isArray(value)) fail(`${field} must be an array`);
  return value;
}

/**
 * Validate the complete semantic diagram shape before anything is normalized,
 * laid out or written to storage.
 */
export function validateDiagram(input) {
  if (!isObject(input)) fail('the diagram must be an object');

  for (const key of FORBIDDEN_DIAGRAM_KEYS) {
    if (key in input) fail(`"${key}" is generated by the backend and is not allowed`);
  }

  const title = text(input.title, 'title', { max: 200 });
  const caption = text(input.caption, 'caption', { required: false, max: 300 });

  const rawNodes = array(input.nodes, 'nodes');
  if (rawNodes.length === 0) fail('at least one node is required');

  const nodeIds = new Set();
  const usedIds = new Set();
  const nodes = rawNodes.map((node, index) => {
    if (!isObject(node)) fail(`nodes[${index}] must be an object`);
    for (const key of FORBIDDEN_NODE_KEYS) {
      if (key in node) fail(`node "${node.id || index}" cannot include "${key}"`);
    }

    const id = identifier(node.id, `nodes[${index}].id`);
    if (nodeIds.has(id)) fail(`duplicate node id "${id}"`);
    nodeIds.add(id);
    usedIds.add(id);

    const type = text(node.type, `node "${id}" type`, { max: 64 }).toLowerCase();
    const label = text(node.label, `node "${id}" label`, { max: 100 });
    const description = text(node.description, `node "${id}" description`, {
      required: false,
      max: 300,
    });

    return { id, type, label, description };
  });

  const rawEdges = array(input.edges, 'edges');
  const edgeIds = new Set();
  const edges = rawEdges.map((edge, index) => {
    if (!isObject(edge)) fail(`edges[${index}] must be an object`);
    for (const key of FORBIDDEN_LAYOUT_KEYS) {
      if (key in edge) fail(`edge "${edge.id || index}" cannot include "${key}"`);
    }

    const id = identifier(edge.id, `edges[${index}].id`);
    if (edgeIds.has(id)) fail(`duplicate edge id "${id}"`);
    if (usedIds.has(id)) fail(`edge id "${id}" is not unique in the diagram`);
    edgeIds.add(id);
    usedIds.add(id);

    const source = identifier(edge.source, `edge "${id}" source`);
    const target = identifier(edge.target, `edge "${id}" target`);
    if (!nodeIds.has(source)) fail(`edge "${id}" references unknown source "${source}"`);
    if (!nodeIds.has(target)) fail(`edge "${id}" references unknown target "${target}"`);

    const type = edge.type === undefined
      ? 'sync'
      : String(edge.type).trim().toLowerCase();
    if (!EDGE_TYPES.has(type)) {
      fail(`edge "${id}" type must be one of ${DIAGRAM_EDGE_TYPES.join(', ')}`);
    }

    const label = text(edge.label, `edge "${id}" label`, { required: false, max: 100 });
    return { id, source, target, label, type };
  });

  return { title, caption, nodes, edges };
}
